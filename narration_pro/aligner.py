"""WhisperX CTC forced alignment; rejects incomplete/misaligned transcripts."""
from __future__ import annotations
import json
import re
import subprocess
from pathlib import Path
from typing import Any
from pydantic import BaseModel, Field

class AlignmentError(RuntimeError):
    pass

class WordTimestamp(BaseModel):
    word: str
    start_s: float = Field(ge=0)
    end_s: float = Field(gt=0)
    score: float | None = None

class AlignmentResult(BaseModel):
    words: list[WordTimestamp]
    audio_path: str
    transcript: str
    language: str
    alignment_model: str
    duration_s: float = Field(gt=0)
    token_coverage: float = Field(ge=0, le=1)
    method: str = "whisperx_ctc"  # generated by backend, never proportional timings

def _tokens(text: str) -> list[str]:
    return re.findall(r"[a-z0-9]+(?:'[a-z0-9]+)?", text.casefold())

def _lcs_length(a: list[str], b: list[str]) -> int:
    prev=[0] * (len(b)+1)
    for token in a:
        cur=[0]
        for j, other in enumerate(b, 1):
            cur.append(prev[j-1]+1 if token == other else max(prev[j],cur[-1]))
        prev=cur
    return prev[-1]

def _duration(path: Path) -> float:
    try:
        proc=subprocess.run(["ffprobe","-v","error","-show_entries","format=duration",
                             "-of","default=nw=1:nk=1",str(path)],capture_output=True,text=True,check=True)
        value=float(proc.stdout.strip())
        if value <= 0: raise ValueError("zero duration")
        return value
    except (OSError,ValueError,subprocess.CalledProcessError) as exc:
        raise AlignmentError("could not probe audio") from exc

class WhisperXAligner:
    def __init__(self, language="en", device="cpu", *, min_token_coverage=0.95,
                 backend: Any | None = None):
        if device != "cpu": raise AlignmentError("CPU only")
        self.language, self.device = language, device
        self.min_token_coverage = min_token_coverage
        self.backend = backend
        self._model = self._metadata = None

    def _load(self):
        if self.backend is None:
            try:
                import whisperx
            except ImportError as exc:
                raise AlignmentError("whisperx==3.8.6 not installed") from exc
            self.backend=whisperx
        if self._model is None:
            self._model, self._metadata = self.backend.load_align_model(language_code=self.language,device=self.device)
        return self._model,self._metadata

    def align(self, audio_path: Path, transcript: str) -> AlignmentResult:
        audio_path=Path(audio_path)
        if not audio_path.is_file(): raise AlignmentError("audio missing")
        if not transcript.strip(): raise AlignmentError("transcript empty")
        duration=_duration(audio_path)
        model,metadata=self._load()
        try:
            audio=self.backend.load_audio(str(audio_path))
            answer=self.backend.align([{"start":0.0,"end":duration,"text":transcript}],
                        model,metadata,audio,"cpu",return_char_alignments=False)
        except Exception as exc:
            raise AlignmentError("CTC alignment failed: "+type(exc).__name__) from exc
        if not isinstance(answer,dict): raise AlignmentError("invalid alignment response")
        aligned=[]
        previous_end=0.0
        for segment in answer.get("segments",[]):
            for item in segment.get("words",[]):
                if item.get("start") is None or item.get("end") is None:
                    continue
                try:
                    word=WordTimestamp(word=str(item.get("word","")).strip(),
                            start_s=float(item["start"]),end_s=float(item["end"]),
                            score=float(item["score"]) if item.get("score") is not None else None)
                except Exception as exc:
                    raise AlignmentError("invalid word timestamps") from exc
                if not word.word or word.end_s <= word.start_s or word.end_s > duration+0.08:
                    raise AlignmentError("bad aligned word interval")
                if word.start_s < previous_end-0.08:
                    raise AlignmentError("nonmonotonic aligned words")
                previous_end=word.end_s
                aligned.append(word)
        expected=_tokens(transcript)
        actual=_tokens(" ".join(w.word for w in aligned))
        coverage=_lcs_length(expected,actual)/len(expected) if expected else 0.0
        if not aligned or coverage < self.min_token_coverage:
            raise AlignmentError(f"forced alignment incomplete: transcript token coverage={coverage:.3f}")
        model_name=metadata.get("model_name", "whisperx_ctc") if isinstance(metadata,dict) else getattr(metadata,"model_name","whisperx_ctc")
        return AlignmentResult(words=aligned,audio_path=str(audio_path),transcript=transcript,
                               language=self.language,alignment_model=str(model_name),duration_s=duration,
                               token_coverage=coverage)

def save_word_timestamps(result: AlignmentResult, output_path: Path):
    output_path.parent.mkdir(parents=True,exist_ok=True)
    output_path.write_text(result.model_dump_json(indent=2),encoding="utf-8")
