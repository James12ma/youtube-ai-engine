"""Real wildlife video clips from Wikimedia Commons, with licence checks.

Only public-domain, CC0 and CC BY clips (commercial reuse allowed, no
ShareAlike) without Restrictions/NonFree flags are accepted. Every clip keeps
its title, author, licence, licence URL and file page for the credits. No
AI-generated footage is produced or substituted here.
"""
from __future__ import annotations
import json
import re
from pathlib import Path
from urllib.parse import urlparse
import httpx
from channel.commons import API, USER_AGENT, _clean, license_allowed

ALLOWED_HOSTS = {'upload.wikimedia.org'}
MAX_CLIP_BYTES = 150_000_000
_AI_HINT = re.compile(r'\b(ai[- ]generated|generated by ai|midjourney|stable diffusion|sora|synthetic|render(ed)?|cgi|animation|3d model)\b', re.I)


def _best_derivative(info: dict) -> dict | None:
    """Prefer a 1080p or 720p transcode Commons already made (VP9/WebM or MP4)."""
    derivs = info.get('derivatives') or []
    best = None
    for d in derivs:
        src = d.get('src') or ''
        h = int(d.get('height') or 0)
        if urlparse(src).hostname not in ALLOWED_HOSTS or urlparse(src).scheme != 'https':
            continue
        if not (d.get('type') or '').startswith('video/') or h > 1080:
            continue
        if best is None or h > int(best.get('height') or 0):
            best = d
    if best is None and urlparse(info.get('url') or '').hostname in ALLOWED_HOSTS:
        best = {'src': info['url'], 'height': info.get('height'), 'width': info.get('width'), 'type': info.get('mime')}
    return best


def search_clips(client: httpx.Client, terms: str, *, limit: int = 50, min_height: int = 720,
                 min_seconds: float = 4.0) -> tuple[list[dict], dict]:
    params = {'action': 'query', 'format': 'json', 'formatversion': '2', 'generator': 'search',
              'gsrsearch': f'filetype:video {terms}', 'gsrnamespace': '6', 'gsrlimit': str(limit),
              'prop': 'videoinfo', 'viprop': 'url|size|mime|extmetadata|derivatives|mediatype'}
    r = client.get(API, params=params, headers={'User-Agent': USER_AGENT}, timeout=30)
    r.raise_for_status()
    pages = r.json().get('query', {}).get('pages', [])
    clips, rejects = [], {}
    for page in sorted(pages, key=lambda p: p.get('index', 999)):
        info = (page.get('videoinfo') or [{}])[0]
        meta = info.get('extmetadata') or {}
        lic = _clean((meta.get('LicenseShortName') or {}).get('value'))
        desc = _clean((meta.get('ImageDescription') or {}).get('value'))
        title = page.get('title', '')
        height = int(info.get('height') or 0)
        duration = float(info.get('duration') or 0)
        why = ('not_video' if (info.get('mediatype') or '').upper() != 'VIDEO' else
               'license' if not license_allowed(lic) or str((meta.get('NonFree') or {}).get('value') or '').lower() == 'true' else
               'restricted' if _clean((meta.get('Restrictions') or {}).get('value')) else
               'ai_or_cgi' if _AI_HINT.search(title + ' ' + desc) else
               'low_res' if height < min_height else
               'too_short' if duration < min_seconds else '')
        deriv = None if why else _best_derivative(info)
        if not why and deriv is None:
            why = 'no_download'
        if why:
            rejects[why] = rejects.get(why, 0) + 1
            continue
        clips.append({'title': title, 'duration_s': round(duration, 1), 'width': info.get('width'),
                      'height': height, 'license': lic,
                      'license_url': _clean((meta.get('LicenseUrl') or {}).get('value')),
                      'author': _clean((meta.get('Artist') or {}).get('value')) or 'Unknown author',
                      'description': desc[:200], 'page': info.get('descriptionurl') or '',
                      'download': deriv['src'], 'download_height': deriv.get('height'), 'search_terms': terms})
    return clips, rejects


def audit(species: list[str], out: Path) -> list[dict]:
    rows = []
    with httpx.Client(trust_env=True) as client:
        for terms in species:
            try:
                clips, rejects = search_clips(client, terms)
            except (httpx.HTTPError, ValueError) as exc:
                rows.append({'species': terms, 'error': type(exc).__name__}); continue
            rows.append({'species': terms, 'usable_clips': len(clips),
                         'usable_seconds': round(sum(c['duration_s'] for c in clips), 1),
                         'hd_1080': sum(1 for c in clips if c['height'] >= 1080), 'rejected': rejects,
                         'clips': clips})
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding='utf-8')
    return rows


def download_clip(client: httpx.Client, url: str, dest: Path) -> Path:
    if urlparse(url).hostname not in ALLOWED_HOSTS or urlparse(url).scheme != 'https':
        raise ValueError('download host not allowed')
    with client.stream('GET', url, headers={'User-Agent': USER_AGENT}, timeout=120, follow_redirects=False) as r:
        r.raise_for_status()
        dest.parent.mkdir(parents=True, exist_ok=True)
        size = 0
        with dest.open('wb') as fh:
            for chunk in r.iter_bytes():
                size += len(chunk)
                if size > MAX_CLIP_BYTES:
                    raise ValueError('clip too large')
                fh.write(chunk)
    return dest


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser(description='Audit free-licence wildlife footage on Wikimedia Commons')
    ap.add_argument('--species', required=True, help='semicolon-separated search terms')
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    rows = audit([s.strip() for s in args.species.split(';') if s.strip()], args.out)
    print(json.dumps([{k: v for k, v in r.items() if k != 'clips'} for r in rows], ensure_ascii=False))
